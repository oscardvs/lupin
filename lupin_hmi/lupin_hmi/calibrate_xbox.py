def load_existing(path: str, mode: str) -> dict:
    """Flatten an existing mode file into the flat mapping dict, falling back
    to built-in defaults for anything missing/absent."""
    m = dict(_DEFAULTS[mode])
    try:
        import yaml
        with open(path) as fh:
            doc = yaml.safe_load(fh) or {}
    except (OSError, Exception):  # noqa: BLE001 - any parse issue → defaults
        return m

    joy = (doc.get('joy_node', {}) or {}).get('ros__parameters', {}) or {}
    tw = (doc.get('teleop_twist_joy_node', {}) or {}).get('ros__parameters', {}) or {}
    arm = (doc.get('arm_teleop', {}) or {}).get('ros__parameters', {}) or {}

    def setif(key, val):
        if val is not None:
            m[key] = val

    setif('device_name', joy.get('device_name'))
    setif('device_id', joy.get('device_id'))
    setif('deadzone', joy.get('deadzone'))
    setif('enable_button', tw.get('enable_button'))
    setif('enable_turbo_button', tw.get('enable_turbo_button'))
    setif('axis_linear_x', (tw.get('axis_linear') or {}).get('x'))
    setif('axis_linear_y', (tw.get('axis_linear') or {}).get('y'))
    setif('axis_angular_yaw', (tw.get('axis_angular') or {}).get('yaw'))
    setif('scale_linear_x', (tw.get('scale_linear') or {}).get('x'))
    setif('scale_linear_y', (tw.get('scale_linear') or {}).get('y'))
    setif('scale_linear_turbo_x', (tw.get('scale_linear_turbo') or {}).get('x'))
    setif('scale_linear_turbo_y', (tw.get('scale_linear_turbo') or {}).get('y'))
    setif('scale_angular_yaw', (tw.get('scale_angular') or {}).get('yaw'))
    setif('scale_angular_turbo_yaw', (tw.get('scale_angular_turbo') or {}).get('yaw'))
    for key in ('shoulder_pan_plus_button', 'shoulder_pan_minus_button',
                'shoulder_lift_plus_button', 'shoulder_lift_minus_button',
                'elbow_axis', 'wrist_axis', 'shoulder_disable_button',
                'shoulder_pan_sign', 'shoulder_lift_sign', 'elbow_sign', 'wrist_sign',
                'gripper_open_axis', 'gripper_close_axis',
                'gripper_open_rest', 'gripper_open_full',
                'gripper_close_rest', 'gripper_close_full'):
        setif(key, arm.get(key))
    return m


# ── joy reader node ───────────────────────────────────────────────────────

class JoyReader(Node):
    def __init__(self):
        super().__init__('calibrate_xbox')
        self._lock = threading.Lock()
        self._axes = None
        self._buttons = None
        self._count = 0
        self.create_subscription(Joy, '/joy', self._cb, 10)

    def _cb(self, msg: Joy) -> None:
        with self._lock:
            self._axes = list(msg.axes)
            self._buttons = list(msg.buttons)
            self._count += 1

    def snapshot(self):
        with self._lock:
            if self._axes is None:
                return None
            return list(self._axes), list(self._buttons), self._count


# ── detection / interaction ───────────────────────────────────────────────

class QuitCalibration(Exception):
    pass


class Calibrator:
    def __init__(self, reader: JoyReader, timeout: float = 8.0):
        self.r = reader
        self.timeout = timeout
        self.base_axes: list[float] = []
        self.base_buttons: list[int] = []

    # -- low-level waits --
    def capture_baseline(self, duration: float = 1.5) -> None:
        print('\nLeave everything CENTERED — sticks released, no buttons, '
              'triggers untouched.')
        input('  Press ENTER to capture the neutral baseline... ')
        samples = []
        end = time.monotonic() + duration
        while time.monotonic() < end:
            snap = self.r.snapshot()
            if snap is not None:
                samples.append(snap)
            time.sleep(0.02)
        if not samples:
            raise RuntimeError('no /joy messages during baseline capture')
        axes_last, btns_last, _ = samples[-1]
        n = len(axes_last)
        # Per-axis median over the window.
        self.base_axes = []
        for i in range(n):
            col = sorted(s[0][i] for s in samples if len(s[0]) > i)
            self.base_axes.append(col[len(col) // 2])
        self.base_buttons = list(btns_last)
        held = [i for i, b in enumerate(self.base_buttons) if b == 1]
        print(f'  baseline: {n} axes, {len(self.base_buttons)} buttons.'
              + (f'  WARNING: buttons {held} read as held.' if held else ''))

    def _wait_release_buttons(self, deadline_extra: float = 0.6) -> None:
        end = time.monotonic() + deadline_extra
        while time.monotonic() < end:
            snap = self.r.snapshot()
            if snap and not any(snap[1]):
                return
            time.sleep(0.02)

    def _wait_axis_settle(self, idx: int, extra: float = 0.8) -> None:
        end = time.monotonic() + extra
        while time.monotonic() < end:
            snap = self.r.snapshot()
            if snap and len(snap[0]) > idx \
                    and abs(snap[0][idx] - self.base_axes[idx]) < 0.3:
                return
            time.sleep(0.02)

    def detect_button(self):
        """Return the index of a single, stably-pressed button (or None)."""
        end = time.monotonic() + self.timeout
        cand = None
        since = 0.0
        while time.monotonic() < end:
            snap = self.r.snapshot()
            if snap is None:
                time.sleep(0.02)
                continue
            _, btns, _ = snap
            pressed = [i for i, b in enumerate(btns)
                       if b == 1 and (i >= len(self.base_buttons)
                                      or self.base_buttons[i] == 0)]
            if len(pressed) == 1:
                if cand == pressed[0]:
                    if time.monotonic() - since >= 0.12:
                        idx = cand
                        self._wait_release_buttons()
                        return idx
                else:
                    cand = pressed[0]
                    since = time.monotonic()
            else:
                cand = None
            time.sleep(0.02)
        return None

    def detect_axis(self, min_dev: float = 0.6):
        """Return (index, sign, value_at_deflection) for the most-deflected
        axis held past a threshold, or None."""
        end = time.monotonic() + self.timeout
        cand = None
        sign = 0
        since = 0.0
        while time.monotonic() < end:
            snap = self.r.snapshot()
            if snap is None:
                time.sleep(0.02)
                continue
            axes, _, _ = snap
            best_i, best_dev = None, 0.0
            for i, a in enumerate(axes):
                base = self.base_axes[i] if i < len(self.base_axes) else 0.0
                dev = a - base
                if abs(dev) > abs(best_dev):
                    best_i, best_dev = i, dev
            if best_i is not None and abs(best_dev) >= min_dev:
                s = 1 if best_dev > 0 else -1
                if cand == best_i and sign == s:
                    if time.monotonic() - since >= 0.12:
                        val = axes[best_i]
                        self._wait_axis_settle(best_i)
                        return best_i, s, val
                else:
                    cand, sign, since = best_i, s, time.monotonic()
            else:
                cand, sign = None, 0
            time.sleep(0.02)
        return None

    # -- step orchestration --
    def _step(self, title: str, instruction: str, detector):
        while True:
            print(f'\n▶ {title}')
            print(f'  {instruction}')
            choice = input('  ENTER = start  ·  s = skip (keep current)  ·  '
                           'q = quit: ').strip().lower()
            if choice == 'q':
                raise QuitCalibration
            if choice == 's':
                print('  → skipped (kept current value).')
                return None
            print('  … go! (waiting for input)')
            result = detector()
            if result is None:
                print('  ✗ nothing detected within the timeout.')
                again = input('  r = retry  ·  s = skip  ·  q = quit: ').strip().lower()
                if again == 'q':
                    raise QuitCalibration
                if again == 's':
                    return None
                continue
            print(f'  ✓ detected {self._describe(result)}')
            confirm = input('  ENTER = accept  ·  r = retry  ·  s = skip  ·  '
                            'q = quit: ').strip().lower()
            if confirm == '':
                return result
            if confirm == 'q':
                raise QuitCalibration
            if confirm == 's':
                return None
            # otherwise loop and retry

    @staticmethod
    def _describe(result) -> str:
        if isinstance(result, int):
            return f'buttons[{result}]'
        idx, sign, val = result
        return f'axes[{idx}]  (direction {"+" if sign > 0 else "-"}, value {val:+.2f})'

    def button_step(self, title, instruction):
        return self._step(title, instruction, self.detect_button)

    def axis_step(self, title, instruction):
        return self._step(title, instruction, self.detect_axis)

    def trigger_step(self, title, instruction):
        """Detect a trigger: index + fully-pulled value, then sample its true
        resting value (which joy_node only reports correctly after the first
        physical event). Returns (idx, rest, full) or None."""
        res = self._step(title, instruction, self.detect_axis)
        if res is None:
            return None
        idx, _sign, full = res
        print('  release the trigger and leave it alone…')
        time.sleep(1.2)
        snap = self.r.snapshot()
        rest = snap[0][idx] if snap and len(snap[0]) > idx else self.base_axes[idx]
        print(f'  rest={rest:+.2f}  full={full:+.2f}')
        return idx, rest, full


def run_walk(cal: Calibrator, m: dict) -> dict:
    """Run the full interactive sequence, overlaying detected values onto m."""
    cal.capture_baseline()

    # Drive — buttons
    b = cal.button_step('Dead-man (LB)',
                        'Press & HOLD the LEFT BUMPER (LB) — the button you hold to drive.')
    if b is not None:
        m['enable_button'] = b
        m['shoulder_disable_button'] = b  # same physical button by design
    b = cal.button_step('Turbo (RB)',
                        'Press & HOLD the RIGHT BUMPER (RB) — the boost button.')
    if b is not None:
        m['enable_turbo_button'] = b

    # Drive — sticks (direction matters)
    r = cal.axis_step('Left stick — FORWARD',
                      'Push the LEFT stick fully FORWARD and hold.')
    if r:
        idx, sign, _ = r
        m['axis_linear_x'] = idx
        m['scale_linear_x'] = sign * abs(m['scale_linear_x'] or 0.2)
        m['scale_linear_turbo_x'] = sign * abs(m['scale_linear_turbo_x'] or 0.6)
    r = cal.axis_step('Left stick — LEFT (strafe)',
                      'Push the LEFT stick fully to the LEFT and hold.')
    if r:
        idx, sign, _ = r
        m['axis_linear_y'] = idx
        m['scale_linear_y'] = sign * abs(m['scale_linear_y'] or 0.2)
        m['scale_linear_turbo_y'] = sign * abs(m['scale_linear_turbo_y'] or 0.6)
    r = cal.axis_step('Right stick — LEFT (turn left)',
                      'Push the RIGHT stick fully to the LEFT (turn-in-place left) and hold.')
    if r:
        idx, sign, _ = r
        m['axis_angular_yaw'] = idx
        m['scale_angular_yaw'] = sign * abs(m['scale_angular_yaw'] or 0.7)
        m['scale_angular_turbo_yaw'] = sign * abs(m['scale_angular_turbo_yaw'] or 1.4)

    # Arm — face buttons (direction is the button, no sign)
    for key, title, instr in (
        ('shoulder_pan_plus_button', 'Shoulder PAN +', 'Press the RIGHT face button (B) → pan +.'),
        ('shoulder_pan_minus_button', 'Shoulder PAN -', 'Press the LEFT face button (X) → pan -.'),
        ('shoulder_lift_plus_button', 'Shoulder LIFT +', 'Press the TOP face button (Y) → lift +.'),
        ('shoulder_lift_minus_button', 'Shoulder LIFT -', 'Press the BOTTOM face button (A) → lift -.'),
    ):
        b = cal.button_step(title, instr)
        if b is not None:
            m[key] = b

    # Arm — D-pad axes (direction → joint +)
    r = cal.axis_step('Elbow (D-pad UP)', 'Press & hold the D-pad UP.')
    if r:
        idx, sign, _ = r
        m['elbow_axis'] = idx
        m['elbow_sign'] = sign
    r = cal.axis_step('Wrist (D-pad LEFT)', 'Press & hold the D-pad LEFT.')
    if r:
        idx, sign, _ = r
        m['wrist_axis'] = idx
        m['wrist_sign'] = sign

    # Gripper — triggers (index + rest/full)
    t = cal.trigger_step('Gripper OPEN (RT)', 'Pull the RIGHT trigger (RT) fully and hold.')
    if t:
        idx, rest, full = t
        m['gripper_open_axis'] = idx
        m['gripper_open_rest'] = float(rest)
        m['gripper_open_full'] = float(full)
    t = cal.trigger_step('Gripper CLOSE (LT)', 'Pull the LEFT trigger (LT) fully and hold.')
    if t:
        idx, rest, full = t
        m['gripper_close_axis'] = idx
        m['gripper_close_rest'] = float(rest)
        m['gripper_close_full'] = float(full)
    return m


def warn_collisions(m: dict) -> None:
    axis_uses = {
        'left-stick fwd/back': m['axis_linear_x'],
        'left-stick strafe': m['axis_linear_y'],
        'right-stick yaw': m['axis_angular_yaw'],
        'elbow D-pad': m['elbow_axis'],
        'wrist D-pad': m['wrist_axis'],
    }
    seen = {}
    for name, idx in axis_uses.items():
        seen.setdefault(idx, []).append(name)
    dupes = {i: names for i, names in seen.items() if len(names) > 1}
    if dupes:
        print('\n⚠  axis collisions (same index used twice):')
        for i, names in dupes.items():
            print(f'     axes[{i}] ← {", ".join(names)}')
    btn_uses = {
        'pan+': m['shoulder_pan_plus_button'], 'pan-': m['shoulder_pan_minus_button'],
        'lift+': m['shoulder_lift_plus_button'], 'lift-': m['shoulder_lift_minus_button'],
        'turbo': m['enable_turbo_button'],
    }
    seen = {}
    for name, idx in btn_uses.items():
        seen.setdefault(idx, []).append(name)
    dupes = {i: names for i, names in seen.items() if len(names) > 1}
    if dupes:
        print('⚠  button collisions:')
        for i, names in dupes.items():
            print(f'     buttons[{i}] ← {", ".join(names)}')


# ── SDL device enumeration ────────────────────────────────────────────────

def enumerate_sdl_devices() -> list:
    try:
        out = subprocess.run(['ros2', 'run', 'joy', 'joy_enumerate_devices'],
                             capture_output=True, text=True, timeout=25)
    except (subprocess.SubprocessError, OSError):
        return []
    devs = []
    for line in out.stdout.splitlines():
        parts = [p.strip() for p in line.split(':')]
        if len(parts) >= 5 and parts[0].isdigit():
            devs.append({
                'id': int(parts[0]),
                'gamepad': parts[2].lower() == 'true',
                'name': ':'.join(parts[4:]).strip(),
            })
    return devs


def choose_device(forced_id):
    devs = enumerate_sdl_devices()
    if forced_id is not None:
        name = next((d['name'] for d in devs if d['id'] == forced_id), 'unknown')
        return forced_id, name
    if not devs:
        print('  (could not enumerate SDL devices — assuming device_id 0)')
        return 0, 'unknown'
    pads = [d for d in devs if d['gamepad']] or devs
    if len(pads) == 1:
        print(f"  using SDL device {pads[0]['id']}: {pads[0]['name']}")
        return pads[0]['id'], pads[0]['name']
    print('\nMultiple controllers found:')
    for d in pads:
        print(f"   [{d['id']}] {d['name']}{'  (gamepad)' if d['gamepad'] else ''}")
    while True:
        sel = input('  Pick device id: ').strip()
        if sel.isdigit() and any(d['id'] == int(sel) for d in pads):
            chosen = next(d for d in pads if d['id'] == int(sel))
            return chosen['id'], chosen['name']


