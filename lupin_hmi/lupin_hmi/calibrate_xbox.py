def _source_config_dirs(runtime_path: str) -> list:
    """Best-effort locate the SOURCE config dir(s) so calibration persists
    across a clean rebuild (the runtime copy lives in build/ via a symlink)."""
    dirs = []
    # (a) Derived from this module's real location — hits when the installed
    #     python package is symlinked back to src.
    try:
        cand = os.path.normpath(os.path.join(
            os.path.dirname(os.path.realpath(__file__)), '..', 'config'))
        if os.path.isdir(cand):
            dirs.append(cand)
    except OSError:
        pass
    # (b) Walk up from the runtime copy (…/build|install/lupin_hmi/config) to
    #     the workspace root, then find src/**/lupin_hmi/config.
    real = os.path.realpath(runtime_path)
    for marker in ('/build/', '/install/'):
        if marker in real:
            ws = real.split(marker)[0]
            for cand in glob.glob(os.path.join(ws, 'src', '**', 'lupin_hmi', 'config'),
                                  recursive=True):
                if os.path.isdir(cand):
                    dirs.append(cand)
            break
    return dirs


def write_config(text: str, config_dir: str, mode: str) -> list:
    """Write the live runtime copy and any locatable source copy, backing up
    existing files. Returns [(path, kind), …] with kind in {'runtime','source'}."""
    fname = f'xbox_config.{mode}.yaml'
    runtime_path = os.path.join(config_dir, fname)
    targets = [(runtime_path, 'runtime')]
    for src_dir in _source_config_dirs(runtime_path):
        targets.append((os.path.join(src_dir, fname), 'source'))

    written, seen = [], set()
    for path, kind in targets:
        real = os.path.realpath(path)
        if real in seen:
            continue
        seen.add(real)
        if os.path.exists(path):
            shutil.copy2(path, path + '.bak')
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w') as fh:
            fh.write(text)
        written.append((path, kind))
    return written


# ── main ──────────────────────────────────────────────────────────────────

def main(args=None) -> int:
    parser = argparse.ArgumentParser(
        prog='calibrate_xbox', description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--mode', choices=['auto', 'usb', 'bluetooth'], default='auto',
                        help='Which mapping to calibrate. auto = detect transport.')
    parser.add_argument('--config-dir', default=None,
                        help='Override the config dir (default: lupin_hmi share/config).')
    parser.add_argument('--device-id', type=int, default=None,
                        help='Force the SDL device id (skip enumeration prompt).')
    parser.add_argument('--timeout', type=float, default=8.0,
                        help='Per-control detection timeout in seconds (default 8).')
    parser.add_argument('--print-only', action='store_true',
                        help='Print the resulting file instead of writing it.')
    parser.add_argument('--yes', action='store_true',
                        help='Skip the final confirmation prompt.')
    parser.add_argument('--force', action='store_true',
                        help='Skip the "is teleop running?" safety check.')
    parser.add_argument('--list', action='store_true',
                        help='List detected pads + SDL devices and exit.')
    opts = parser.parse_args(args=args)

    if opts.list:
        print('Transport detection:', describe_pads())
        print('Detected mode      :', detect_pad_mode())
        print('SDL devices:')
        for d in enumerate_sdl_devices():
            print(f"   [{d['id']}] {d['name']}  gamepad={d['gamepad']}")
        return 0

    # Resolve mode.
    mode = opts.mode
    if mode == 'auto':
        detected = detect_pad_mode()
        print(f'Transport detection: {describe_pads()}')
        if detected is None:
            print('Could not detect the transport. Re-run with --mode usb|bluetooth.')
            return 2
        mode = detected
    print(f'\n=== Calibrating the {mode.upper()} mapping ===')

    config_dir = opts.config_dir or os.path.join(
        get_package_share_directory('lupin_hmi'), 'config')
    target = os.path.join(config_dir, f'xbox_config.{mode}.yaml')
    m = load_existing(target, mode)

    # Pick the SDL device for our own joy_node.
    device_id, device_name = choose_device(opts.device_id)
    m['device_id'] = device_id
    if device_name and device_name != 'unknown':
        m['device_name'] = device_name

    print('\n⚠  Make sure xbox_teleop is STOPPED (Ctrl-C the teleop launch).')
    print('   This tool runs its own joy_node; if teleop is up the robot will')
    print('   move while you press buttons.')
    input('   Press ENTER once teleop is stopped… ')

    rclpy.init()
    reader = JoyReader()
    executor = SingleThreadedExecutor()
    executor.add_node(reader)
    spin = threading.Thread(target=executor.spin, daemon=True)
    spin.start()

    joy_proc = None
    rc = 0
    try:
        # Best-effort safety check (graph discovery; may be blind under some
        # DDS setups, hence the explicit prompt above).
        time.sleep(1.5)
        if not opts.force:
            names = reader.get_node_names()
            clashing = [n for n in ('arm_teleop', 'teleop_twist_joy_node') if n in names]
            if clashing:
                print(f'\n✗ teleop appears to be running ({", ".join(clashing)}). '
                      'Stop it first, or pass --force.')
                return 3

        # Spawn our own joy_node (raw: deadzone 0 so we see true axis values).
        joy_proc = subprocess.Popen(
            ['ros2', 'run', 'joy', 'joy_node', '--ros-args',
             '-r', '__node:=calibrate_joy_node',
             '-p', f'device_id:={device_id}',
             '-p', 'deadzone:=0.0',
             '-p', 'autorepeat_rate:=20.0'],
            stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, text=True)

        print('\nStarting joy_node and waiting for /joy…')
        deadline = time.monotonic() + 6.0
        while time.monotonic() < deadline and reader.snapshot() is None:
            if joy_proc.poll() is not None:
                err = (joy_proc.stderr.read() or '').strip()
                print(f'✗ joy_node exited early.\n{err}')
                return 4
            time.sleep(0.1)
        if reader.snapshot() is None:
            print('✗ no /joy messages. Is the pad on and is the SDL device id '
                  'right? Try `--list`.')
            return 4

        try:
            m = run_walk(Calibrator(reader, timeout=opts.timeout), m)
        except QuitCalibration:
            print('\nAborted — nothing written.')
            return 1

        warn_collisions(m)
        text = render_config(mode, m)
        print('\n' + '─' * 70)
        print(text.rstrip())
        print('─' * 70)

        if opts.print_only:
            print('\n(--print-only: not writing)')
            return 0
        if not opts.yes:
            ans = input(f'\nWrite this to xbox_config.{mode}.yaml? [y/N] ').strip().lower()
            if ans not in ('y', 'yes'):
                print('Not written.')
                return 0

        written = write_config(text, config_dir, mode)
        print('\n✓ wrote:')
        for path, kind in written:
            tag = 'live now' if kind == 'runtime' else 'source — persists rebuilds'
            print(f'   [{kind:7}] {path}  ({tag})')
        wrote_source = any(k == 'source' for _, k in written)
        print('\nNext: relaunch teleop —  ros2 launch lupin_hmi xbox_teleop.launch.py')
        if not wrote_source:
            print('NOTE: could not locate the source copy — a clean rebuild would revert')
            print('      this. Save the YAML printed above to '
                  f'src/.../lupin_hmi/config/xbox_config.{mode}.yaml to persist it.')
    finally:
        if joy_proc is not None:
            joy_proc.terminate()
            try:
                joy_proc.wait(timeout=3)
            except subprocess.TimeoutExpired:
                joy_proc.kill()
        executor.shutdown()
        reader.destroy_node()
        rclpy.shutdown()
    return rc


if __name__ == '__main__':
    sys.exit(main())
