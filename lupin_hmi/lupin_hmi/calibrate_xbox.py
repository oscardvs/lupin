"""Interactive Xbox-controller calibration for lupin_hmi teleop.

Why this exists
---------------
The button/axis index order an Xbox pad presents to ``joy_node`` (SDL2) depends
on the kernel driver, which depends on the transport: a USB cable binds
``xpad`` (standard layout) while Bluetooth binds the Microsoft-HID path (a
shifted layout). Switching between them silently remaps every control. This
tool re-probes the *currently connected* pad and rewrites the matching config
file (``config/xbox_config.{usb,bluetooth}.yaml``) that xbox_teleop loads.

What it does
------------
1. Detects whether the pad is on USB or Bluetooth (lupin_hmi.pad_detect).
2. Spawns its OWN joy_node (so the full teleop stack stays down and the robot
   can't move while you press buttons) and reads /joy.
3. Walks you through each control one at a time, detecting the index and — for
   sticks/D-pad/triggers — the direction, so the saved mapping reproduces the
   documented control scheme regardless of how the indices shifted.
4. Writes the matching mode file (with a .bak backup), leaving the other
   mode's file untouched.

Run it with the teleop launch STOPPED:

    ros2 run lupin_hmi calibrate_xbox

Useful flags: --mode {auto,usb,bluetooth}, --print-only, --device-id N,
--list, --yes, --force, --config-dir PATH.
"""

